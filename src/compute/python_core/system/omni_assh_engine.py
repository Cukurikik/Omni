# ── SSH Config Generator ──────────────────────────────────────────────────

class SSHConfigGenerator:
    """Generate OpenSSH config blocks from host definitions."""

    @staticmethod
    def generate_block(host: SSHHost) -> str:
        """Generate a single SSH config block."""
        lines = [f"Host {host.name}"]
        lines.append(f"    HostName {host.hostname}")
        lines.append(f"    Port {host.port}")
        if host.user:
            lines.append(f"    User {host.user}")
        if host.identity_file:
            lines.append(f"    IdentityFile {host.identity_file}")
        if host.proxy_jump:
            lines.append(f"    ProxyJump {host.proxy_jump}")
        if host.forward_agent:
            lines.append("    ForwardAgent yes")
        lines.append(f"    ServerAliveInterval {host.keep_alive_interval}")
        lines.append(f"    ServerAliveCountMax {host.keep_alive_count}")
        lines.append(f"    ConnectTimeout {host.connect_timeout}")
        lines.append("")
        return "\n".join(lines)

    @staticmethod
    def generate_full_config(hosts: List[SSHHost]) -> str:
        """Generate a complete SSH config file."""
        header = "# ═══════════════════════════════════════════\n"
        header += "# Generated by OMNI ASSH Engine\n"
        header += f"# Generated at: {time.strftime('%Y-%m-%d %H:%M:%S')}\n"
        header += "# ═══════════════════════════════════════════\n\n"
        blocks = [SSHConfigGenerator.generate_block(h) for h in hosts]
        return header + "\n".join(blocks)

    def diagnostics(self):
        """Return engine health status for the OmniEngineRegistry."""
        return {
            "engine": "SSHConfigGenerator",
            "version": "1.0.0",
            "status": "operational",
            "capabilities": []
        }


# ── SSH Config Parser ──────────────────────────────────────────────────────

class SSHConfigParser:
    """Parse existing ~/.ssh/config files."""

    @staticmethod
    def parse(config_path: str = "") -> List[Dict]:
        """Parse an SSH config file into structured data."""
        if not config_path:
            config_path = os.path.expanduser("~/.ssh/config")
        if not os.path.isfile(config_path):
            return []

        hosts = []
        current = None

        with open(config_path, "r", encoding="utf-8") as f:
            for line in f:
                stripped = line.strip()
                if not stripped or stripped.startswith("#"):
                    continue

                if stripped.lower().startswith("host ") and not stripped.lower().startswith("hostname"):
                    if current:
                        hosts.append(current)
                    current = {"name": stripped[5:].strip(), "options": {}}
                elif current and "=" in stripped or " " in stripped:
                    parts = stripped.split(None, 1)
                    if len(parts) == 2:
                        current["options"][parts[0].lower()] = parts[1]

        if current:
            hosts.append(current)
        return hosts

    @staticmethod
    def count_hosts(config_path: str = "") -> int:
        """Execute count hosts operation for SSHConfigParser engine."""
        return len(SSHConfigParser.parse(config_path))

    def diagnostics(self):
        """Return engine health status for the OmniEngineRegistry."""
        return {
            "engine": "SSHConfigParser",
            "version": "1.0.0",
            "status": "operational",
            "capabilities": []
        }


# ── SSH Connectivity Tester ────────────────────────────────────────────────

class SSHConnectivityTester:
    """Test SSH connectivity to remote hosts."""

    @staticmethod
    def test_port(hostname: str, port: int = 22, timeout: float = 5) -> SSHConnectionTest:
        """Test if an SSH port is open and get the banner."""
        result = SSHConnectionTest(host=hostname, port=port)
        start = time.perf_counter()
        try:
            with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
                s.settimeout(timeout)
                conn = s.connect_ex((hostname, port))
                result.latency_ms = round((time.perf_counter() - start) * 1000, 2)
                result.reachable = conn == 0

                if result.reachable:
                    try:
                        s.settimeout(3)
                        banner = s.recv(256).decode("utf-8", errors="replace").strip()
                        result.ssh_banner = banner
                    except Exception:
                        pass
        except socket.gaierror as e:
            result.error = f"DNS resolution failed: {str(e)[:128]}"
        except Exception as e:
            result.error = str(e)[:128]
        return result

    @staticmethod
    def test_ssh_command(hostname: str, user: str = "",
                          timeout: int = 10) -> Dict:
        """Test SSH connectivity using the ssh command."""
        target = f"{user}@{hostname}" if user else hostname
        try:
            r = subprocess.run(
                ["ssh", "-o", "ConnectTimeout=5", "-o", "StrictHostKeyChecking=no",
                 "-o", "BatchMode=yes", target, "echo OMNI_SSH_OK"],
                capture_output=True, text=True, timeout=timeout,
            )
            return {
                "target": target,
                "connected": "OMNI_SSH_OK" in r.stdout,
                "exit_code": r.returncode,
                "output": r.stdout.strip()[:256],
                "error": r.stderr.strip()[:256],
            }
        except FileNotFoundError:
            return {"target": target, "error": "ssh command not found"}
        except subprocess.TimeoutExpired:
            return {"target": target, "error": "Connection timeout"}
        except Exception as e:
            return {"target": target, "error": str(e)[:128]}

    def diagnostics(self):
        """Return engine health status for the OmniEngineRegistry."""
        return {
            "engine": "SSHConnectivityTester",
            "version": "1.0.0",
            "status": "operational",
            "capabilities": []
        }


# ── Host Registry (JSON) ──────────────────────────────────────────────────

class HostRegistry:
    """Persistent host definitions."""

    def __init__(self, registry_path: str = ""):
        """Initialize HostRegistry engine with default configuration."""
        if not registry_path:
            try:
                registry_path = os.path.join(os.path.dirname(__file__), "..", ".ssh_hosts.json")
            except NameError:
                registry_path = os.path.join(os.getcwd(), ".ssh_hosts.json")
        self.path = registry_path

    def load(self) -> List[Dict]:
        """Execute load operation for HostRegistry engine."""
        if os.path.isfile(self.path):
            with open(self.path, "r", encoding="utf-8") as f:
                return json.load(f)
        return []

    def save(self, hosts: List[Dict]):
        """Execute save operation for HostRegistry engine."""
        with open(self.path, "w", encoding="utf-8") as f:
            json.dump(hosts, f, indent=2)

    def add(self, host: SSHHost) -> Dict:
        """Execute add operation for HostRegistry engine."""
        hosts = self.load()
        hosts.append({
            "name": host.name, "hostname": host.hostname,
            "port": host.port, "user": host.user,
            "identity_file": host.identity_file,
            "proxy_jump": host.proxy_jump,
            "tags": host.tags, "description": host.description,
        })
        self.save(hosts)
        return {"added": host.name, "total": len(hosts)}

    def diagnostics(self):
        """Return engine health status for the OmniEngineRegistry."""
        return {
            "engine": "HostRegistry",
            "version": "1.0.0",
            "status": "operational",
            "capabilities": []
        }


# ── The Main Engine ─────────────────────────────────────────────────────────

class OmniAsshEngine:
    """
    OMNI ASSH Engine — Zero-Mock Advanced SSH Config & Connection Manager.

    Capabilities (all native — socket, subprocess, os):
      - SSH config parsing (~/.ssh/config)
      - SSH config generation from host definitions
      - Multi-hop gateway config (ProxyJump)
      - Port connectivity testing with banner grab
      - SSH command testing
      - JSON host registry persistence
    """

    def __init__(self):
        """Initialize Assh engine with default configuration."""
        self.generator = SSHConfigGenerator()
        self.parser = SSHConfigParser()
        self.tester = SSHConnectivityTester()
        self.registry = HostRegistry()

    def parse_config(self) -> List[Dict]:
        """Execute parse config operation for Assh engine."""
        return self.parser.parse()

    def test_host(self, hostname: str, port: int = 22) -> Dict:
        """Execute test host operation for Assh engine."""
        result = self.tester.test_port(hostname, port)
        return {
            "host": result.host, "port": result.port,
            "reachable": result.reachable, "latency_ms": result.latency_ms,
            "banner": result.ssh_banner, "error": result.error,
        }

    def check_ssh_binary(self) -> Dict:
        """Execute check ssh binary operation for Assh engine."""
        try:
            r = subprocess.run(["ssh", "-V"], capture_output=True, text=True, timeout=5)
            version = r.stderr.strip() or r.stdout.strip()
            return {"installed": True, "version": version}
        except FileNotFoundError:
            return {"installed": False, "version": ""}

    def diagnostics(self) -> Dict:
        """Return engine health status for the OmniEngineRegistry."""
        ssh = self.check_ssh_binary()
        config_hosts = self.parser.count_hosts()
        return {
            "engine": "OmniAsshEngine",
            "status": "active",
            "ssh": ssh,
            "config_hosts": config_hosts,
            "registry_hosts": len(self.registry.load()),
            "capabilities": ["config_parse", "config_generate", "proxy_jump",
                             "port_test", "banner_grab", "ssh_test", "host_registry"],
        }


