class PlatformType(Enum):
    DOCKER = "docker"
    FLY_IO = "fly"
    RAILWAY = "railway"
    RENDER = "render"
    VERCEL = "vercel"
    NETLIFY = "netlify"
    AWS_ECS = "aws-ecs"
    AWS_LAMBDA = "aws-lambda"
    AZURE_CONTAINER_APPS = "azure"
    GCP_CLOUD_RUN = "gcp"
    DIGITALOCEAN_APP = "digitalocean"
    KUBERNETES = "k8s"
    VPS_BARE_METAL = "vps"
    COOLIFY = "coolify"
    CAPROVER = "caprover"


@dataclass
class PlatformConfig:
    """Configuration for a deployment platform."""
    platform: PlatformType
    name: str
    description: str
    config_file: str
    deploy_command: str
    supports_docker: bool = True
    supports_static: bool = False
    supports_serverless: bool = False
    supports_gpu: bool = False
    free_tier: bool = False
    regions: list[str] = field(default_factory=list)
    env_vars: dict[str, str] = field(default_factory=dict)
    min_memory_mb: int = 256
    port: int = 3000


