# COMPONENT 4: Universal Deployer Orchestrator
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
class OmniUniversalDeployer:
    """
    Universal deployment orchestrator.
    Replaces GCP-only with support for 14+ platforms.
    
    Usage:
        deployer = OmniUniversalDeployer()
        deployer.generate_config("railway")
        deployer.generate_all_configs()
        deployer.deploy("fly")
    """
    
    def __init__(self, app_name: str = "omni-framework", port: int = 3000,
                 output_dir: str = "."):
        self.app_name = app_name
        self.port = port
        self.output_dir = output_dir
        self.generated_configs: list[str] = []
        
        print("🌍 [UNIVERSAL-DEPLOYER] Multi-Platform Deployment System initialized")
        print(f"   App: {app_name} | Port: {port}")
        print(f"   Platforms available: {len(PLATFORM_REGISTRY)}")
    
    def list_platforms(self) -> list[dict]:
        """List all supported deployment platforms."""
        platforms = []
        for key, p in PLATFORM_REGISTRY.items():
            platforms.append({
                "id": key,
                "name": p.name,
                "description": p.description,
                "config_file": p.config_file,
                "deploy_command": p.deploy_command,
                "free_tier": p.free_tier,
            })
        return platforms
    
    def generate_config(self, platform_id: str, env_vars: dict = None) -> str:
        """Generate deployment config for a specific platform."""
        if platform_id not in PLATFORM_REGISTRY:
            raise ValueError(
                f"Platform '{platform_id}' not supported. "
                f"Available: {', '.join(PLATFORM_REGISTRY.keys())}"
            )
        
        platform = PLATFORM_REGISTRY[platform_id]
        gen = ConfigGenerator
        
        generators = {
            "docker": lambda: gen.docker_compose(self.app_name, self.port, env_vars),
            "railway": lambda: gen.railway_json(self.app_name, self.port),
            "render": lambda: gen.render_yaml(self.app_name, self.port),
            "vercel": lambda: gen.vercel_json(self.app_name),
            "netlify": lambda: gen.netlify_toml(self.app_name),
            "aws-ecs": lambda: gen.aws_ecs_json(self.app_name, self.port),
            "azure": lambda: gen.azure_deploy_json(self.app_name, self.port),
            "gcp": lambda: gen.gcp_cloudrun_json(self.app_name, self.port),
            "digitalocean": lambda: gen.digitalocean_app_yaml(self.app_name, self.port),
            "coolify": lambda: gen.coolify_json(self.app_name, self.port),
            "caprover": lambda: gen.caprover_definition(self.app_name),
        }
        
        if platform_id in generators:
            content = generators[platform_id]()
            config_path = os.path.join(self.output_dir, platform.config_file)
            self.generated_configs.append(config_path)
            print(f"   ✅ [{platform.name}] Config generated: {platform.config_file}")
            return content
        
        # Platforms with existing configs
        print(f"   ℹ️ [{platform.name}] Uses existing config: {platform.config_file}")
        return ""
    
    def generate_all_configs(self) -> dict[str, str]:
        """Generate configs for ALL supported platforms."""
        print(f"\n   🌐 Generating configs for {len(PLATFORM_REGISTRY)} platforms...")
        configs = {}
        for platform_id in PLATFORM_REGISTRY:
            try:
                content = self.generate_config(platform_id)
                if content:
                    configs[platform_id] = content
            except Exception as e:
                print(f"   ⚠️ [{platform_id}] Error: {e}")
        
        print(f"\n   📋 Generated {len(configs)} platform configs")
        return configs
    
    def get_deploy_command(self, platform_id: str) -> str:
        """Get the deploy command for a platform."""
        if platform_id in PLATFORM_REGISTRY:
            return PLATFORM_REGISTRY[platform_id].deploy_command
        return f"echo 'Unknown platform: {platform_id}'"
    
    def deploy_info(self, platform_id: str) -> dict:
        """Get full deployment info for a platform."""
        platform = PLATFORM_REGISTRY.get(platform_id)
        if not platform:
            return {"error": f"Platform '{platform_id}' not found"}
        
        return {
            "platform": platform.name,
            "config_file": platform.config_file,
            "deploy_command": platform.deploy_command,
            "free_tier": platform.free_tier,
            "supports_docker": platform.supports_docker,
            "regions": platform.regions,
            "min_memory_mb": platform.min_memory_mb,
        }


