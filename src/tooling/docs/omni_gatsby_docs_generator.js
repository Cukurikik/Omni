// OMNI Tooling & UI Layer
// Gatsby Docs Generator
// Based on gatsbyjs/gatsby. Used to generate static documentation sites for Omni packages.

const fs = require('fs');
const path = require('path');

class OmniDocsGenerator {
    constructor(sourceDir, outDir) {
        this.sourceDir = sourceDir;
        this.outDir = outDir;
        console.log(`OMNI JS: Initializing Static Docs Generator (Source: ${sourceDir})`);
    }

    // Simulates the Gatsby GraphQL data extraction phase
    async extractData() {
        console.log("OMNI JS: Scanning source files for JSDoc and Omni tags...");
        
        // In reality, this would use AST parsers
        const simulatedData = [
            { id: "1", title: "Universal Binary Setup", content: "Instructions for C-ABI..." },
            { id: "2", title: "Monadic Error Handling", content: "Rule Section 3.1..." }
        ];

        return simulatedData;
    }

    // Simulates the static HTML rendering phase
    async renderPages(nodes) {
        if (!fs.existsSync(this.outDir)) {
            fs.mkdirSync(this.outDir, { recursive: true });
        }

        nodes.forEach(node => {
            const html = `
            <!DOCTYPE html>
            <html lang="en">
            <head><title>${node.title} - Omni Docs</title></head>
            <body>
                <h1>${node.title}</h1>
                <p>${node.content}</p>
                <footer>Generated by Omni Universal Engine</footer>
            </body>
            </html>
            `;
            
            const filename = `${node.title.replace(/\s+/g, '-').toLowerCase()}.html`;
            fs.writeFileSync(path.join(this.outDir, filename), html);
            console.log(`OMNI JS: Generated static page: ${filename}`);
        });
    }

    async build() {
        try {
            const nodes = await this.extractData();
            await this.renderPages(nodes);
            console.log("OMNI JS: Static documentation build complete.");
        } catch (err) {
            console.error("OMNI JS Error: Build failed.", err);
        }
    }
}

module.exports = OmniDocsGenerator;

if (require.main === module) {
    const generator = new OmniDocsGenerator('./src', './public/docs');
    generator.build();
}
