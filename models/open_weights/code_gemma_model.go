func (c *CodeGemmaModel) resolveEndpoint() string {
	return fmt.Sprintf("https://%s-aiplatform.googleapis.com/v1/projects/%s/locations/%s/publishers/google/models/%s:predict",
		c.Config.Region, c.Config.ProjectID, c.Config.Region, c.Config.Variant)
}

func min(a, b int) int {
	if a < b {
		return a
	}
	return b
}
